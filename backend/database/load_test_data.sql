\set ON_ERROR_STOP on

-- Test data: three users; Developer access is shared across both partners.
\set profile_image_url 'https://profileimageurl.com'

\set user1_uuid '10432000-0000-4000-8000-000000000001'
\set user1_email 'EMAIL1'
\set user1_name 'Test User 1'
\set user1_developer false

\set user2_uuid '10432000-0000-4000-8000-000000000002'
\set user2_email 'EMAIL2'
\set user2_name 'Test User 2'
\set user2_developer true

\set user3_uuid '10432000-0000-4000-8000-000000000003'
\set user3_email 'EMAIL3'
\set user3_name 'Test User 3'
\set user3_developer true

-- The department catalog entry must already exist.
\set department_gc_org_id 2222

\set partner1_uuid '10430000-0000-4000-8000-000000000001'
\set partner1_name_en 'QA Partner One'
\set partner1_name_fr 'Partenaire de test un'

\set partner2_uuid '10430000-0000-4000-8000-000000000002'
\set partner2_name_en 'QA Partner Two'
\set partner2_name_fr 'Partenaire de test deux'

-- One application under Partner One; two under Partner Two.
\set application1_uuid '10431000-0000-4000-8000-000000000001'
\set application1_partner_uuid :partner1_uuid
\set application1_name_en 'QA App One'
\set application1_name_fr 'Application de test un'

\set application2_uuid '10431000-0000-4000-8000-000000000002'
\set application2_partner_uuid :partner2_uuid
\set application2_name_en 'QA App Two'
\set application2_name_fr 'Application de test deux'

\set application3_uuid '10431000-0000-4000-8000-000000000003'
\set application3_partner_uuid :partner2_uuid
\set application3_name_en 'QA App Three'
\set application3_name_fr 'Application de test trois'

-- Load steps. All fixture values come from the data section above.
SELECT bool_and(email = lower(btrim(email)) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$') AS test_emails_valid
FROM (VALUES (:'user1_email'), (:'user2_email'), (:'user3_email')) AS test_user(email) \gset
\if :test_emails_valid
\else
  DO $$ BEGIN RAISE EXCEPTION 'Replace EMAIL1, EMAIL2 and EMAIL3 with lowercase test emails before running.'; END $$;
\endif

BEGIN;

-- Check the required schema and shared-role scope before inserting anything.
DO $$
BEGIN
  IF to_regclass('public.partner_group') IS NULL
    OR to_regclass('public.application') IS NULL
    OR to_regclass('public.partner_group_role') IS NULL THEN
    RAISE EXCEPTION 'Required tables are missing. Apply the portal migrations through 0012_partner_developer_write first.';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.partner_group_role AS role_link
    JOIN public.role AS role ON role.id = role_link.role_id
    JOIN public.partner_group AS partner ON partner.id = role_link.partner_group_id
    WHERE role.name = 'Partner Developer' AND NOT role.is_deleted
      AND NOT role_link.is_deleted AND NOT partner.is_deleted
  ) THEN
    RAISE EXCEPTION 'Partner Developer already has partner access. Use a clean test dataset for this seed.';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.access_policy
    WHERE subject = 'Partner Developer' AND resource = 'applications'
      AND action IN ('read', 'write') AND NOT is_deleted
    HAVING count(*) = 2 AND count(DISTINCT action) = 2 AND bool_and(deleted_at IS NULL)
  ) THEN
    RAISE EXCEPTION 'The existing Developer applications/read and applications/write policies are required.';
  END IF;
END;
$$;

-- 1. Users. Integer IDs are generated by PostgreSQL; onboarding fields stay unset.
INSERT INTO public."user" (
  uuid, email, username, name, profile_image_url, created_at,
  is_deleted, is_superuser, enabled
)
SELECT user_uuid::uuid, email, email, name, :'profile_image_url', CURRENT_TIMESTAMP,
  false, false, false
FROM (VALUES
  (:'user1_uuid', :'user1_email', :'user1_name'),
  (:'user2_uuid', :'user2_email', :'user2_name'),
  (:'user3_uuid', :'user3_email', :'user3_name')
) AS test_user(user_uuid, email, name);

-- 2. Partners. Resolve the department's integer ID from its catalog number.
INSERT INTO public.partner_group (uuid, department_id, name_en, name_fr, created_at, is_deleted)
SELECT partner_uuid::uuid,
  (SELECT id FROM public.department WHERE gc_org_id = :'department_gc_org_id'::integer AND NOT is_deleted AND deleted_at IS NULL),
  name_en, name_fr, CURRENT_TIMESTAMP, false
FROM (VALUES
  (:'partner1_uuid', :'partner1_name_en', :'partner1_name_fr'),
  (:'partner2_uuid', :'partner2_name_en', :'partner2_name_fr')
) AS test_partner(partner_uuid, name_en, name_fr);

-- 3. Applications, linked to their partners by UUID.
INSERT INTO public.application (uuid, partner_group_id, name_en, name_fr, created_at, is_deleted)
SELECT application_uuid::uuid,
  (SELECT id FROM public.partner_group WHERE uuid = partner_uuid::uuid),
  name_en, name_fr, CURRENT_TIMESTAMP, false
FROM (VALUES
  (:'application1_uuid', :'application1_partner_uuid', :'application1_name_en', :'application1_name_fr'),
  (:'application2_uuid', :'application2_partner_uuid', :'application2_name_en', :'application2_name_fr'),
  (:'application3_uuid', :'application3_partner_uuid', :'application3_name_en', :'application3_name_fr')
) AS test_application(application_uuid, partner_uuid, name_en, name_fr);

-- 4. Link both partners to Developer. Every existing Developer also receives this scope.
INSERT INTO public.partner_group_role (partner_group_id, role_id, uuid, created_at, is_deleted)
SELECT (SELECT id FROM public.partner_group WHERE uuid = partner_uuid::uuid),
  (SELECT id FROM public.role WHERE name = 'Partner Developer' AND NOT is_deleted AND deleted_at IS NULL),
  gen_random_uuid(), CURRENT_TIMESTAMP, false
FROM (VALUES (:'partner1_uuid'), (:'partner2_uuid')) AS test_partner(partner_uuid);

-- 5. Assign Developer only to the users selected in the data section.
INSERT INTO public.user_role (user_id, role_id, uuid, created_at, is_deleted)
SELECT (SELECT id FROM public."user" WHERE uuid = user_uuid::uuid),
  (SELECT id FROM public.role WHERE name = 'Partner Developer' AND NOT is_deleted AND deleted_at IS NULL),
  gen_random_uuid(), CURRENT_TIMESTAMP, false
FROM (VALUES
  (:'user1_uuid', :'user1_developer'::boolean),
  (:'user2_uuid', :'user2_developer'::boolean),
  (:'user3_uuid', :'user3_developer'::boolean)
) AS test_user(user_uuid, grant_developer)
WHERE grant_developer;

COMMIT;
